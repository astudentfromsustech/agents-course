#!/usr/bin/env python3
"""Inject the folding sidebar contents into every course page.

Regenerable: rewrites whatever sits between the TOC markers, so re-running after
adding a chapter is the way to update them all. Never hand-edit the injected block.

    python3 resources/_build_toc.py          # build
    python3 resources/_build_toc.py --check  # report, change nothing
"""
import os, re, sys, html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START, END = "<!--TOC:START — generated by resources/_build_toc.py, do not edit-->", "<!--TOC:END-->"

# ordered registry: (number, label, path or None if unwritten)
CHAPTERS = [
    ("00", "Overview",     "00_overview/00_overview.html"),
    ("01", "Transformer",  "01_transformer/00_representation.html"),
    ("01a","— tokens → vectors","01_transformer/01_tokens_to_vectors.html"),
    ("01b","— self-attention","01_transformer/02_self_attention.html"),
    ("01c","— position","01_transformer/03_position.html"),
    ("01d","— architecture","01_transformer/04_transformer.html"),
    ("02", "LLM",          "02_LLM/02_LLM.html"),
    ("03", "Agent",        "03_agent/03_agent.html"),
    ("04", "Context",      "04_context/04_context.html"),
    ("05", "Knowledge",    "05_knowledge/05_knowledge.html"),
    ("06", "Multi-agent",  "06_multi_agent/06_multi_agent.html"),
    ("07", "Evaluation",   "07_evaluation/07_evaluation.html"),
    ("08", "Capstone",     None),
]

EXT_A = re.compile(r'<a\s+(?![^>]*\btarget=)([^>]*href="https?://[^"]*"[^>]*)>')

def external_new_tab(src):
    """Every link that LEAVES the course opens a new tab; internal nav stays in place.
    rel=noopener is the security half — without it the opened page can reach window.opener."""
    return EXT_A.sub(lambda m: '<a target="_blank" rel="noopener noreferrer" %s>' % m.group(1), src)


GH = "https://github.com/astudentfromsustech/agents-course/blob/main"
COLAB = "https://colab.research.google.com/github/astudentfromsustech/agents-course/blob/main"

# (tag, label, href, kind) — kind "nb" gets the notebook glyph and opens in Colab
PRACTICE = [
    ("p0", "attention, step by step", f"{COLAB}/practice/p0_attention/walkthrough.ipynb", "nb"),
    ("p0", "write it yourself",       f"{GH}/practice/p0_attention/attention_lab.py",      "py"),
    ("p1", "heads learn a circuit",   f"{COLAB}/practice/p1_induction_heads/induction.ipynb", "nb"),
    ("p2", "a ViT reads digits",      f"{COLAB}/practice/p2_vit_mnist/vit_mnist.ipynb",    "nb"),
    ("", "run it on your own Mac",     f"{GH}/practice/RUNNING.md",                          "doc"),
]


def slug(t):
    s = re.sub(r"<[^>]*>", "", t)
    s = html.unescape(s).lower()
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return ("s-" + s)[:48].rstrip("-")

def headings(src):
    """(id, level, text) for h2/h3 in document order; assigns ids where missing.
    Returns the possibly-modified source too."""
    out, pos = [], 0
    def repl(m):
        attrs, text = m.group(2), m.group(3)
        lvl = int(m.group(1))
        got = re.search(r'id="([^"]+)"', attrs)
        if got:
            hid = got.group(1); new = m.group(0)
        else:
            hid = slug(text)
            new = f"<h{lvl}{attrs} id=\"{hid}\">{text}</h{lvl}>"
        label = re.sub(r"<[^>]*>", "", text).strip()
        out.append((hid, lvl, label))
        return new
    src = re.sub(r"<h([23])([^>]*)>(.*?)</h\1>", repl, src, flags=re.S)
    return src, out

def aside(page_rel, subs):
    """page_rel: path of this page relative to course root, or '' for the landing page."""
    depth = page_rel.count("/")
    up = "../" * depth
    L = [START,
         '<aside class="toc" id="toc" data-open="0">',
         '  <button class="toc-btn" id="tocBtn" aria-expanded="false" aria-controls="tocPanel" title="Contents (c)">'
         '<span class="toc-ico" aria-hidden="true"></span><span class="toc-lbl">Contents</span></button>',
         '  <nav class="toc-panel" id="tocPanel" aria-label="Course contents">',
         f'    <a class="toc-home{" here" if page_rel=="" else ""}" href="{up}agents.html">Developing agents</a>',
         '    <ol class="toc-ch">']
    for num, label, path in CHAPTERS:
        here = (path == page_rel)
        cls = []
        if here: cls.append("here")
        if path is None: cls.append("todo")
        c = f' class="{" ".join(cls)}"' if cls else ""
        n = "" if num in ("01a", "01b", "01c", "01d") else f'<i>{num}</i>'
        if path:
            L.append(f'      <li{c}><a href="{up}{path}">{n}{label}</a>')
        else:
            L.append(f'      <li{c}><span>{n}{label}</span>')
        if here and subs:
            L.append('        <ul class="toc-sec">')
            for hid, lvl, text in subs:
                L.append(f'          <li class="l{lvl}"><a href="#{hid}">{html.escape(text)}</a></li>')
            L.append('        </ul>')
        L.append('      </li>')
    L.append('    </ol>')
    L.append('    <p class="toc-lab">practice</p>')
    L.append('    <ul class="toc-prac">')
    for tag, label, href, kind in PRACTICE:
        L.append(f'      <li class="{kind}"><a href="{href}">'
                 f'<i>{tag}</i><span>{label}</span></a></li>')
    L.append('    </ul>')
    L += ['  </nav>', '</aside>', END]
    return "\n".join(L)

def build(check=False):
    pages = [p for _, _, p in CHAPTERS if p] + ["agents.html"]
    changed = []
    for rel in pages:
        fp = os.path.join(ROOT, rel)
        if not os.path.exists(fp):
            print(f"  skip (missing)  {rel}"); continue
        src = orig = open(fp).read()
        page_rel = "" if rel == "agents.html" else rel
        src, hs = headings(src)
        subs = hs if page_rel else []
        block = aside(page_rel, subs)

        if START in src:
            src = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, src, flags=re.S)
        else:
            anchor = '<div class="wrap">'
            if anchor not in src:
                print(f"  SKIP (no .wrap) {rel}"); continue
            src = src.replace(anchor, anchor + "\n" + block, 1)

        src = external_new_tab(src)   # after injection, so sidebar links are covered too

        up = "../" * page_rel.count("/")
        tag = f'<script src="{up}resources/toc.js" defer></script>'
        if "resources/toc.js" not in src:
            src = src.replace("</body>", tag + "\n</body>", 1)

        if src != orig:
            changed.append(rel)
            if not check:
                open(fp, "w").write(src)
        ext = len(re.findall(r'<a[^>]*target="_blank"[^>]*href="https?://', src))
        print(f"  {'WOULD UPDATE' if check else 'ok':<12} {rel:<38} {len(subs)} sections · {ext} ext-links → new tab")
    print(("\n%d page(s) would change." if check else "\n%d page(s) written.") % len(changed))
    return 1 if (check and changed) else 0

if __name__ == "__main__":
    sys.exit(build(check="--check" in sys.argv))
